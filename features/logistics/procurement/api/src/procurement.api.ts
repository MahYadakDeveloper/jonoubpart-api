/**
 * Discrepancies in quantity, item type, or damaged goods are decided inside
 * this module (procurement), not by the warehouse.
 */
export interface ProcurementApi {
  /**
   * Called by the warehouse when a shipment arrives, to report what was
   * physically received against an expected reception.
   *
   * - `expectedReceptionId` is mandatory on every call.
   * - `lines` holds the healthy items. Each line identifies its product in one of
   *   these ways:
   *
   *   1. a known product id with a quantity;
   *   2. a barcode plus descriptive attributes (name, brand, ...), which may be a
   *      new barcode for an existing product or an entirely new product. The
   *      warehouse does not need to know which; this module decides whether to
   *      define a new product or attach the barcode to an existing one;
   *   3. no barcode at all: the warehouse generates a stock label identifier and
   *      sends it with the product attributes. If the product cannot be
   *      identified, one or more images must be attached to the line.
   * - `damagedLines` is a separate list from `lines`. Damaged units are NOT added
   *   to stock. This module quarantines each unit individually with its own
   *   label number, and returns those labels on the matching damaged lines.
   *
   * Mismatches against the expected reception (quantity, item type, damage) are
   * resolved here.
   */
  receiveShipment(cmd: ReceiveShipmentCommand): Promise<void>;
}

/** How a line identifies its product. At least one form must be provided. */
export type ReceivedProductRef =
  | { productId: string } // already-defined product
  | { barcode: string; attributes: ProductAttributes } // known or new barcode
  | { stockLabelId: string; attributes: ProductAttributes }; // no barcode: label generated by the warehouse

export interface ProductAttributes {
  name?: string;
  brand?: string;
  [key: string]: unknown;
}

export interface ReceivedLine {
  product: ReceivedProductRef;
  quantity: number;
  /** Required when the product cannot be identified from its attributes. */
  imageUrls?: string[];
}

export interface DamagedLine {
  product: ReceivedProductRef;
  /** Images specific to this damaged line. */
  quarantineLabelIds: [];
  imageUrls: string[];
}

export interface ReceiveShipmentCommand {
  lines: ReceivedLine[];
  damagedLines?: DamagedLine[];
}

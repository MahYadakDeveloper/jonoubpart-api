/**
 * # =============================================================================
 *
 * WAREHOUSE API CONTRACT
 *
 * The warehouse is a self-contained domain. It knows stock, labels, packages
 * and physical handovers. It does NOT know what an "order", a "purchase" or a
 * "customer account" is. Consumers (order, procurement, POS, terminal UI...)
 * adapt their own concepts to this contract, never the other way around.
 *
 * ## CORE CONCEPTS
 *
 * - Warehouse: the system has one or more. Every command that touches stock or a
 *   terminal names the warehouse it acts on (`warehouseId`). The warehouse
 *   never guesses it from context. Choosing WHICH warehouse serves a request
 *   (nearest, one with stock, ...) is the caller's decision.
 * - referenceId: an opaque correlation key owned by the CALLER. The warehouse
 *   never interprets it (it may be an order id, a purchase id, a transfer id, a
 *   POS sale id...). It is unique per (warehouseId, referenceId) and is what
 *   makes commands idempotent and links reserve -> ship, and collect/expect ->
 *   arrival -> check-in.
 * - Stock label: a unique id for ONE physical unit, generated by the warehouse.
 *   Starts with "S" for a regular stock unit and "Q" for a quarantined
 *   (damaged) unit. Used for goods that have no barcode, and for every damaged
 *   unit. Goods with a barcode are tracked by barcode + quantity instead.
 * - Package: the unit that leaves or enters the warehouse. When goods are
 *   shipped, the warehouse packs the lines into a package with a `packageId`
 *   and remembers which lines, destination and recipient belong to it. Only the
 *   `packageId` (plus destination/source data) is shared with the outside:
 *   delivery systems and terminals never see lines.
 *
 * ## THE THREE PORTS (ways goods physically enter or leave)
 *
 * 1. POS port: in-person, immediate movements at a point of sale. No package, no
 *    intermediate state (`issue`, `receive`, `lookup`).
 * 2. Delivery port: the system's own delivery. The warehouse knows only addresses
 *    and lines; the delivery side knows only package ids. Commands: `ship`
 *    (out) and `collect` (in).
 * 3. Terminal port: goods enter or leave directly at the warehouse terminal, with
 *    no relation to the system's own delivery (e.g. a freight network drops
 *    cargo off, or a customer picks a prepared package up in person).
 *    Operations: `arrival`, `checkIn`, `packages`, `handOver`.
 *
 * ## GENERAL RULES
 *
 * - Business decisions stay with consumers. The warehouse reports physical facts
 *   (what was reserved, shipped, received, damaged). Deciding what a shortage,
 *   an unexpected item or a damaged unit MEANS (refund, re-order, claim...) is
 *   the consumer's job, taken from the events at the bottom.
 * - Commands are idempotent by (warehouseId, referenceId): repeating a command
 *   with the same data has no additional effect. Reusing a referenceId with
 *   different data is an error.
 * - Commands are all-or-nothing: if any line cannot be satisfied the whole
 *   command fails and nothing changes.
 * - Long-running outcomes (delivered, failed, arrived, checked in) are not return
 *   values. They are published as events (see `WarehouseEvent`).
 */

import type {
  CollectSource,
  DispatchDestination,
} from '@logistics/delivery/api';

/* -------------------------------------------------------------------------- */
/*                                 PRIMITIVES                                 */
/* -------------------------------------------------------------------------- */

export type WarehouseId = string;

/**
 * Globally unique. It identifies the package AND implicitly the warehouse that
 * owns it.
 */
export type PackageId = string;

/**
 * Identifies exactly one physical unit, generated by the warehouse. "S..." =
 * regular stock unit, "Q..." = quarantined (damaged) unit.
 */
export type StockLabel = string;

/**
 * Mixed into every command that acts on one warehouse's stock or terminal.
 * Commands that carry a `packageId` do not need it: the package already belongs
 * to exactly one warehouse.
 */
export interface WarehouseScoped {
  warehouseId: WarehouseId;
}

/* -------------------------------------------------------------------------- */
/*                               ITEMS AND LINES                              */
/* -------------------------------------------------------------------------- */

/**
 * A request line for goods the warehouse already knows how to find.
 *
 * - `label`: one specific unit (stock or quarantine label). Quantity is always
 *   exactly one, so none is given.
 * - `barcode`: `quantity` units of whatever is stocked under that barcode.
 *
 * Product identity (name, brand, which product owns a barcode) belongs to the
 * consumer features. The warehouse only resolves barcodes and labels to
 * physical stock.
 */
export type Line =
  | { kind: 'label'; label: StockLabel }
  | { kind: 'barcode'; barcode: string; quantity: number };

/**
 * Free-form descriptive data for an item seen during check-in (name, brand,
 * ...).
 */
export interface ItemAttributes {
  name?: string;
  brand?: string;
  [key: string]: unknown;
}

/* -------------------------------------------------------------------------- */
/*                         STOCK AND MOVEMENT COMMANDS                        */
/* -------------------------------------------------------------------------- */

/**
 * Sets aside available stock for a future shipment, so nobody else can take it.
 * Reserved stock is not available to others but is still physically here. Fails
 * (and reserves nothing) if any line lacks enough available stock.
 */
export interface ReserveCommand {
  /**
   * Unique per warehouse. Later `release` and `ship` refer to the reservation
   * by it.
   */
  referenceId: string;
  lines: Line[];
}

/**
 * Cancels a reservation and makes the stock available again. Releasing an
 * unknown or already released/shipped reference has no effect.
 */
export interface ReleaseCommand {
  referenceId: string;
}

export interface PickupRecipient {
  name: string;
  phone: string;
}

/**
 * Sends goods out of the warehouse as ONE package.
 *
 * - If a reservation exists for (warehouseId, referenceId) it is consumed and
 *   `lines` must match it. If none exists, the warehouse reserves and ships in
 *   one step (and fails if stock is insufficient).
 * - The warehouse then picks and packs the lines and creates the package.
 *   Delivery or pickup of the package follows `destination`.
 * - The package leaves stock when it is handed over (event `package.shipped`),
 *   and its final fate is reported by `package.delivered` /
 *   `package.delivery-failed` (for delivery destinations) or by `handOver` (for
 *   `pickup`).
 */
export interface ShipCommand {
  referenceId: string;
  lines: Line[];
  destination:
    | DispatchDestination
    | {
        kind: 'pickup';

        recipient:
          | { kind: 'freight_truck'; note?: string }
          /**
           * The person who receives a package in person, either from a courier
           * at their address or at the warehouse terminal.
           */
          | { kind: 'person'; verificationCode: string };
      };
}

/**
 * Orders our delivery to fetch goods from an address and bring them to this
 * warehouse. The warehouse remembers the lines it EXPECTS under `referenceId`;
 * the delivery side only learns the pickup address and a package id, never the
 * lines. When the goods arrive they are matched by `referenceId` (event
 * `package.arrived`) and must then be checked in (`checkIn`).
 */
export interface CollectCommand {
  referenceId: string;
  lines: Line[];
  source: CollectSource;
}

/**
 * Announces goods that will reach this warehouse WITHOUT a `collect`, for
 * example cargo a freight network will drop at the terminal on its own. It
 * gives `arrival` something to match against. Arrivals without a matching
 * expectation are accepted but flagged as unexpected.
 */
export interface ExpectCommand extends WarehouseScoped {
  referenceId: string;
  lines: Line[];
  /** Carrier waybill number, when known, to help match the arrival. */
  waybillNumber?: string;
}

/* -------------------------------------------------------------------------- */
/*                                  POS PORT                                  */
/* -------------------------------------------------------------------------- */

/**
 * Immediate stock-out for an in-person sale. No package and no reservation
 * step: stock decreases right away, or the command fails.
 */
export interface IssueCommand extends WarehouseScoped {
  /** Opaque POS correlation id (e.g. sale id), used for idempotency and audit. */
  referenceId: string;
  lines: Line[];
}

/**
 * Immediate stock-in at a point of sale, such as an in-store return or shelf
 * replenishment. Only for goods the warehouse can already identify. Newly
 * arriving, unidentified or damaged goods go through `arrival` + `checkIn`.
 */
export interface ReceiveCommand extends WarehouseScoped {
  referenceId: string;
  lines: Line[];
}

/** Resolves a scanned barcode or label in ONE warehouse. */
export interface LookupCommand extends WarehouseScoped {
  /** A barcode, a stock label ("S...") or a quarantine label ("Q..."). */
  code: string;
}

export interface ItemAvailability {
  warehouseId: WarehouseId;
  code: string;
  kind: 'barcode' | 'stock-label' | 'quarantine-label';
  /** Units that can be reserved or issued now. Always 0 for quarantined units. */
  available: number;
  /** Units set aside by reservations, still physically in the warehouse. */
  reserved: number;
}

/* -------------------------------------------------------------------------- */
/*                                  THE API                                   */
/* -------------------------------------------------------------------------- */

export interface WarehouseApi {
  /* ------------------ clients: Order, Procurement (and others) ------------------ */

  /** Sets stock aside under `referenceId`. All-or-nothing. */
  reserve(cmd: ReserveCommand): Promise<void>;

  /** Cancels a reservation and returns the stock to the available pool. */
  release(cmd: ReleaseCommand): Promise<void>;

  /**
   * Packs lines into one package and sends it per `destination`. Returns the
   * package id; later outcomes arrive as events.
   */
  ship(cmd: ShipCommand): Promise<{ packageId: PackageId }>;

  /**
   * Orders our delivery to bring goods from the given source to this warehouse.
   * The outcome arrives as event `package.arrived`.
   */
  collect(cmd: CollectCommand): Promise<void>;

  /**
   * Registers goods that will arrive at the terminal on their own. if
   * referenceId is already exist then the expectation get rewritten
   */
  expect(cmd: ExpectCommand): Promise<void>;

  /* ------------------------------- client: POS ------------------------------- */

  /** Immediate stock-out for an in-person sale. */
  issue(cmd: IssueCommand): Promise<void>;

  /** Immediate stock-in (e.g. in-store return, shelf replenishment). */
  receive(cmd: ReceiveCommand): Promise<void>;

  /**
   * Resolves a scanned barcode/label to an item and its availability, or null
   * if unknown.
   */
  lookup(cmd: LookupCommand): Promise<ItemAvailability | null>;
}

/* -------------------------------------------------------------------------- */
/*                                   EVENTS                                   */
/* -------------------------------------------------------------------------- */

/**
 * Events the warehouse publishes. Consumers subscribe; the warehouse never
 * calls consumers. Every event carries `warehouseId` and, when known, the
 * caller's `referenceId`, so a consumer recognises its own operations.
 */
interface WarehouseEventBase {
  warehouseId: WarehouseId;
  referenceId?: string;
  /** ISO 8601. */
  occurredAt: string;
}

export type WarehouseEvent =
  /**
   * The package left the warehouse (picked up by our courier or handed over at
   * the terminal).
   */
  | (WarehouseEventBase & { type: 'package.shipped'; packageId: PackageId })
  /** The delivery system confirmed the package reached its destination. */
  | (WarehouseEventBase & { type: 'package.delivered'; packageId: PackageId })
  /** Delivery failed; the consumer decides what happens next. */
  | (WarehouseEventBase & {
      type: 'package.delivery-failed';
      packageId: PackageId;
      reason: string;
    })
  /**
   * A package reached the warehouse (via `collect` or the terminal). It still
   * has to be checked in. `expected = false` means no `collect`/`expect`
   * matched it.
   */
  | (WarehouseEventBase & {
      type: 'package.arrived';
      packageId: PackageId;
      expected: boolean;
      waybillNumber?: string;
    })
  /**
   * The real content of a package was recorded. Compare it with what you
   * expected (quantity, item type, damage) to resolve mismatches.
   */
  | (WarehouseEventBase & {
      type: 'package.checked-in';
      packageId: PackageId;
      lines: ReceivedLine[];
      damagedLines: DamagedLine[];
      /** Labels generated by the check-in, in the same order as the lines. */
      result: CheckInResult;
    });
